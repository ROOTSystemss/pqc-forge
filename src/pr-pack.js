import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { scanRepository } from './scanner.js';
import { migrateRepository } from './migrator.js';
import { compareScans } from './baseline.js';
import { scanToSarif } from './sarif.js';
import { createMigrationReceipt, createPrPackReceipt, verifyReceipt } from './breaklab/receipt.js';

const digest = (content) => `sha256:${createHash('sha256').update(content).digest('hex')}`;
const publicMigration = (migration) => ({
  ...migration,
  artifacts: migration.artifacts.map(({ beforeContent, afterContent, ...artifact }) => artifact)
});

function executeGit(args) {
  return new Promise((resolve, reject) => {
    const child = spawn('git', args, { windowsHide: true });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.stderr.on('data', (chunk) => { stderr += chunk; });
    child.once('error', reject);
    child.once('close', (code) => resolve({ code: code ?? 2, stdout, stderr }));
  });
}

function patchPath(file) {
  const normalized = file.replace(/\\/g, '/');
  return /\s/.test(normalized) ? JSON.stringify(normalized) : normalized;
}

async function filePatch(artifact) {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'pqc-forge-diff-'));
  const before = path.join(temporary, 'before');
  const after = path.join(temporary, 'after');
  try {
    await Promise.all([fs.writeFile(before, artifact.beforeContent, 'utf8'), fs.writeFile(after, artifact.afterContent, 'utf8')]);
    const result = await executeGit(['diff', '--no-index', '--no-color', '--unified=3', '--', before, after]);
    if (![0, 1].includes(result.code)) throw new Error(`git diff failed: ${result.stderr.trim()}`);
    if (result.code === 0) return '';
    // Preserve source line endings inside the hunk. Apply commands use a
    // one-command core.autocrlf override so Git does not rewrite those bytes.
    const hunk = result.stdout.slice(result.stdout.indexOf('@@'));
    const label = patchPath(artifact.file);
    // Never trim hunk whitespace: a trailing blank context line is part of the
    // declared line count and removing it creates a corrupt unified diff.
    return `diff --git a/${label} b/${label}\n--- a/${label}\n+++ b/${label}\n${hunk.endsWith('\n') ? hunk : `${hunk}\n`}`;
  } finally {
    await fs.rm(temporary, { recursive: true, force: true });
  }
}

function renderPullRequest(summary) {
  const protocolEvidence = summary.protocolEvidenceIncluded
    ? '- `protocol-lab-receipt.json` provides verified reference-lab OpenSSL/Nginx capability evidence; it is not target-runtime proof.\n'
    : '';
  const runtimeEvidence = summary.targetRuntimeEvidenceIncluded
    ? summary.targetRuntimeEvidenceComplete
      ? `- Target-runtime receipts cover every migrated configuration: ${summary.runtimeCoveredFiles.join(', ')}.\n`
      : `- Target-runtime evidence is partial (${summary.runtimeCoveredFiles.join(', ') || 'none'} covered; ${summary.runtimeUncoveredFiles.join(', ')} still blocked).\n`
    : '- No target-runtime receipt is included; deployment remains blocked pending staging runtime probes.\n';
  return `# PQC migration generated by PQC Forge\n\n## Result\n\n- Files scanned: ${summary.filesScanned}\n- Migration changes: ${summary.changeCount}\n- Findings before: ${summary.beforeFindings}\n- Findings after: ${summary.afterFindings}\n- Findings resolved: ${summary.resolvedFindings}\n- Remaining critical/high: ${summary.remainingBlockingFindings}\n- Production deployment: BLOCKED pending staging and canary validation\n\n## Runtime requirement\n\n${summary.runtimeRequirement}\n\n## Evidence\n\n- \`scan-before.json\` and \`scan-after.json\` provide repository evidence.\n- \`pqc-forge.sarif\` is ready for code-scanning ingestion.\n- \`migration-receipt.json\` binds the planned edits and artifact digests.\n- \`pr-pack-receipt.json\` detects changes to this generated bundle.\n${protocolEvidence}${runtimeEvidence}\n## Apply and rollback\n\nApply with \`git apply migration.patch\`. Roll back with \`git apply -R migration.patch\`. Use the repository's existing line-ending policy, then follow \`DEPLOYMENT_SAFETY.md\` in staging. This pack never authorizes an unattended production deployment.\n`;
}

function renderDeploymentSafety(summary) {
  return `# Deployment safety gate\n\nStatus: **BLOCKED — staging and canary validation required**\n\nRuntime evidence coverage: ${summary.runtimeCoveredFiles.length}/${summary.runtimeCoveredFiles.length + summary.runtimeUncoveredFiles.length} migrated configuration files.\n\nBefore production, an authorized operator must:\n\n1. Apply the patch in an isolated staging copy.\n2. Run \`pqc-forge runtime-probe\` against every patched server configuration in its target runtime.\n3. Verify a staging endpoint negotiates the intended group and detect classical fallback.\n4. Exercise supported modern, legacy, API, browser, and device clients.\n5. Run handshake load, latency, fragmentation, and soak tests.\n6. Deploy to a small canary with explicit failure and latency rollback thresholds.\n7. Verify rollback from the reviewed patch and retain monitoring during gradual rollout.\n\nReference-lab or runtime receipts do not replace client, traffic, canary, or production monitoring evidence.\n`;
}

export async function createPrPack(rootPath, outputPath, { protocolReceiptPath = null, runtimeReceiptPath = null, runtimeReceiptPaths = [] } = {}) {
  const root = path.resolve(rootPath);
  const output = path.resolve(outputPath);
  try {
    const existing = await fs.readdir(output);
    if (existing.length > 0) throw new Error(`Refusing to overwrite non-empty PR pack directory: ${output}`);
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const beforeScan = await scanRepository(root);
  const migrationWithContent = await migrateRepository(root, { includeContent: true });
  if (migrationWithContent.changeCount === 0) throw new Error('No supported migration changes were found; PR pack was not created.');
  const overrides = new Map(migrationWithContent.artifacts.map((artifact) => [artifact.file, artifact.afterContent]));
  const afterScan = await scanRepository(root, { overrides });
  const delta = compareScans(afterScan, beforeScan);
  afterScan.delta = delta;
  const migration = publicMigration(migrationWithContent);
  const migrationReceipt = createMigrationReceipt(migration);
  const requestedRuntimeReceipts = [...runtimeReceiptPaths, ...(runtimeReceiptPath ? [runtimeReceiptPath] : [])];
  const runtimeEvidence = [];
  const coveredFiles = new Set();
  for (const receiptPath of requestedRuntimeReceipts) {
    const receipt = JSON.parse(await fs.readFile(path.resolve(receiptPath), 'utf8'));
    if (receipt.schema !== 'pqc-forge.runtime-receipt/v1' || !verifyReceipt(receipt).valid || !receipt.probe?.verdict?.pass) {
      throw new Error('Target runtime evidence must be a valid, passing PQC Forge runtime-receipt/v1 document.');
    }
    const matched = migration.artifacts.find((artifact) => artifact.afterDigest === receipt.probe.config?.digest);
    if (!matched) throw new Error('Target runtime receipt configuration digest does not match a generated post-migration artifact.');
    if (coveredFiles.has(matched.file)) throw new Error(`Duplicate target runtime evidence for ${matched.file}.`);
    coveredFiles.add(matched.file);
    runtimeEvidence.push({ receipt, file: matched.file });
  }
  const uncoveredFiles = migration.artifacts.map((artifact) => artifact.file).filter((file) => !coveredFiles.has(file));
  const patchParts = [];
  for (const artifact of migrationWithContent.artifacts) patchParts.push(await filePatch(artifact));
  const patch = patchParts.join('\n');
  const summary = {
    schema: 'pqc-forge.pr-pack-summary/v1', repository: root,
    filesScanned: beforeScan.filesScanned, changeCount: migration.changeCount,
    beforeFindings: beforeScan.summary.total, afterFindings: afterScan.summary.total,
    resolvedFindings: delta.summary.resolved,
    remainingBlockingFindings: afterScan.findings.filter((finding) => ['critical', 'high'].includes(finding.severity)).length,
    runtimeRequirement: migration.runtimeRequirement,
    protocolEvidenceIncluded: Boolean(protocolReceiptPath),
    targetRuntimeEvidenceIncluded: runtimeEvidence.length > 0,
    targetRuntimeEvidenceComplete: uncoveredFiles.length === 0,
    runtimeCoveredFiles: [...coveredFiles],
    runtimeUncoveredFiles: uncoveredFiles,
    productionDeploymentAuthorized: false,
    deploymentStatus: 'blocked-pending-staging-and-canary'
  };
  const files = new Map([
    ['scan-before.json', `${JSON.stringify(beforeScan, null, 2)}\n`],
    ['scan-after.json', `${JSON.stringify(afterScan, null, 2)}\n`],
    ['pqc-forge.sarif', `${JSON.stringify(scanToSarif(afterScan), null, 2)}\n`],
    ['migration.patch', patch],
    ['migration-receipt.json', `${JSON.stringify(migrationReceipt, null, 2)}\n`],
    ['PR_DESCRIPTION.md', renderPullRequest(summary)],
    ['DEPLOYMENT_SAFETY.md', renderDeploymentSafety(summary)],
    ['ROLLBACK.md', '# Rollback\n\nFrom the repository root, run:\n\n```sh\ngit apply -R migration.patch\n```\n\nPQC Forge generated this reverse operation from the same reviewed patch. Use the same repository line-ending policy used when applying it.\n']
  ]);
  if (protocolReceiptPath) {
    const protocolReceipt = JSON.parse(await fs.readFile(path.resolve(protocolReceiptPath), 'utf8'));
    if (protocolReceipt.schema !== 'pqc-forge.protocol-lab-receipt/v1' || !verifyReceipt(protocolReceipt).valid) {
      throw new Error('Protocol evidence must be a valid PQC Forge protocol-lab-receipt/v1 document.');
    }
    files.set('protocol-lab-receipt.json', `${JSON.stringify(protocolReceipt, null, 2)}\n`);
  }
  runtimeEvidence.forEach(({ receipt }, index) => {
    const name = runtimeEvidence.length === 1 ? 'runtime-receipt.json' : `runtime-receipt-${index + 1}.json`;
    files.set(name, `${JSON.stringify(receipt, null, 2)}\n`);
  });
  const artifactDigests = [...files].map(([file, content]) => ({ file, digest: digest(content), bytes: Buffer.byteLength(content) }));
  const packReceipt = createPrPackReceipt(summary, artifactDigests);
  files.set('pr-pack-receipt.json', `${JSON.stringify(packReceipt, null, 2)}\n`);
  await fs.mkdir(output, { recursive: true });
  for (const [file, content] of files) await fs.writeFile(path.join(output, file), content, 'utf8');
  return { summary, output, receiptDigest: packReceipt.receiptDigest, files: [...files.keys()] };
}
